async Task CreateTableAsync(string connectionString)
{
    await using var connection = new NpgsqlConnection(connectionString);
    await connection.OpenAsync(); //open connection to the database

    const string sql = $"""
                        CREATE TABLE IF NOT EXISTS Student (
                            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            Name VARCHAR(100) NOT NULL,
                            Age INTEGER,
                            GPA DECIMAL(3,2)
                        );
                        """;

    await using var command = new NpgsqlCommand(sql, connection);
    await command.ExecuteNonQueryAsync(); //sends it to PostgreSQL and executes it
}
async Task AddStudentAsync(string connectionString)
{
    Console.Write("Enter name: ");
    var name = Console.ReadLine();

    Console.Write("Enter age: ");
    var age = int.Parse(Console.ReadLine()!);

    Console.Write("Enter GPA: ");
    var gpa = decimal.Parse(Console.ReadLine()!);

    await using var connection = new NpgsqlConnection(connectionString);
    await connection.OpenAsync(); //open connection to the database

    const string sql = "INSERT INTO Student (Name, Age, GPA) VALUES (@name, @age, @gpa)";

    await using var command = new NpgsqlCommand(sql, connection);
    command.Parameters.AddWithValue("name", name!);
    command.Parameters.AddWithValue("age", age);
    command.Parameters.AddWithValue("gpa", gpa);

    await command.ExecuteNonQueryAsync();
    Console.WriteLine("Student added successfully!");
}
async Task ViewStudentsAsync(string connectionString)
{
    await using var connection = new NpgsqlConnection(connectionString);
    await connection.OpenAsync(); //open connection to the database

    const string sql = "SELECT * FROM Student";

    await using var command = new NpgsqlCommand(sql, connection);
    await using var reader = await command.ExecuteReaderAsync(); // because we’re reading data back. The reader holds all the rows that came back from the database.

    Console.WriteLine("\nId | Name | Age | GPA");
    Console.WriteLine("------------------------");

    while (await reader.ReadAsync())
    {
        var id = reader["Id"];
        var name = reader["Name"];
        var age = reader["Age"];
        var gpa = reader["GPA"];
        Console.WriteLine($"{id} | {name} | {age} | {gpa}");
    }
}
async Task UpdateStudentAsync(string connectionString)
{
    Console.Write("Enter student Id to update: ");
    var id = int.Parse(Console.ReadLine()!);

    Console.Write("Enter new name: ");
    var name = Console.ReadLine();

    Console.Write("Enter new age: ");
    var age = int.Parse(Console.ReadLine()!);

    Console.Write("Enter new GPA: ");
    var gpa = decimal.Parse(Console.ReadLine()!);

    await using var connection = new NpgsqlConnection(connectionString);
    await connection.OpenAsync(); //open connection to the database

    const string sql = "UPDATE Student SET Name = @name, Age = @age, GPA = @gpa WHERE Id = @id";

    await using var command = new NpgsqlCommand(sql, connection);
    command.Parameters.AddWithValue("id", id);
    command.Parameters.AddWithValue("name", name!);
    command.Parameters.AddWithValue("age", age);
    command.Parameters.AddWithValue("gpa", gpa);

    var affected = await command.ExecuteNonQueryAsync();

    if (affected > 0)
        Console.WriteLine("Student updated successfully!");
    else
        Console.WriteLine("No student found with that Id.");
}
async Task DeleteStudentAsync(string connectionString)
{
    Console.Write("Enter student Id to delete: ");
    var id = int.Parse(Console.ReadLine()!);

    await using var connection = new NpgsqlConnection(connectionString);
    await connection.OpenAsync();

    const string sql = "DELETE FROM Student WHERE Id = @id";

    await using var command = new NpgsqlCommand(sql, connection);
    command.Parameters.AddWithValue("id", id);

    var affected = await command.ExecuteNonQueryAsync();

    if (affected > 0)
        Console.WriteLine("Student deleted successfully!");
    else
        Console.WriteLine("No student found with that Id.");
}